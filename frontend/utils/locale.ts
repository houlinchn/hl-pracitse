export function localizedTime(value: string, locale: Locale): string {
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? "—"
    : date.toLocaleString(locale === "en" ? "en-GB" : "zh-CN", {
        hour12: false,
      });
}

