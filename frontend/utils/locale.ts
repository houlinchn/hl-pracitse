export function localizedError(error: unknown, locale: Locale): string {
  const data = (
    error as { data?: { detail?: unknown; fields?: unknown } } | null
  )?.data;
  const key = errorKeys.find((key) => key === data?.detail);
  const detail = translate(key ?? "服务暂时不可用，请稍后重试", locale);
  // Never display upstream HTML, unknown exception text or untrusted field paths.
  const fields =
    key && Array.isArray(data?.fields)
      ? [
          ...new Set(
            data.fields
              .slice(0, 20)
              .map((field: unknown) =>
                translate(
                  typeof field === "string"
                    ? (fieldKeys[field] ?? "字段")
                    : "字段",
                  locale,
                ),
              ),
          ),
        ]
      : [];
  return fields.length
    ? `${detail}${locale === "zh" ? "（" : " ("}${fields.join(locale === "zh" ? "、" : ", ")}${locale === "zh" ? "）" : ")"}`
    : detail;
}

export function localizedReason(
  event: {
    before: string | null;
    after: string;
    channel: string;
    reason: string;
  },
  locale: Locale,
): string {
  // Only these two events have system-generated reasons. Staff prose stays intact.
  const systemDraft =
    event.channel === "web" &&
    event.before === null &&
    event.after === "draft" &&
    event.reason === "创建草稿";
  const systemSubmit =
    event.channel === "web" &&
    event.before === "draft" &&
    event.after === "submitted" &&
    event.reason === "申请人提交申请";
  return systemDraft
    ? translate("创建草稿", locale)
    : systemSubmit
      ? translate("申请人提交申请", locale)
      : event.reason;
}
