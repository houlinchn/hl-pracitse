export type Locale = "zh" | "en";
export type MessageKey = keyof typeof messages;
export const languageStorageKey = "voxnova.applicant-language";
export const validLocale = (value: unknown): Locale =>
  value === "en" ? "en" : "zh";
export const effectiveLocale = (preference: Locale, staff: boolean): Locale =>
  staff ? "zh" : preference;
export const translate = (key: MessageKey | "", locale: Locale): string =>
  key ? messages[key][locale] : "";

type StorageAccess = Pick<Storage, "getItem" | "setItem">;
export function restoreLocale(storage: StorageAccess): Locale {
  try {
    return validLocale(storage.getItem(languageStorageKey));
  } catch {
    return "zh";
  }
}
export function rememberLocale(storage: StorageAccess, value: unknown): Locale {
  const locale = validLocale(value);
  try {
    storage.setItem(languageStorageKey, locale);
  } catch {
    // A blocked/full store must not prevent in-memory language switching.
  }
  return locale;
}
